# Shell session from the video, as a file you can run.
# Each line below was typed at the >>> prompt; the commented lines are
# what Python answered. Run it with:  python3 -i thisfile.py

def f(n): return 3 * n + 5
f(10) / 10
#   3.5
f(100) / 100
#   3.05
f(1000) / 1000
#   3.005
def g(n): return n * n
g(10) / 10
#   10.0
g(100) / 100
#   100.0
g(1000) / 1000
#   1000.0
